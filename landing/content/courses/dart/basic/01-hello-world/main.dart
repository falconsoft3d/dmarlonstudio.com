// Every Dart program starts running in main().
void main() {
  // print() writes a line of text and moves to the next one.
  print('Hello, world!');
  print('Welcome to Dart.');

  // Single or double quotes: both make a string.
  print("It's easy to start.");

  // print() also writes numbers and the result of a sum.
  print(42);
  print(7 * 6);
  print(2 + 3);

  // An empty string leaves a blank line.
  print('');

  // Every instruction ends with a semicolon.
  print('Dart is the language of Flutter apps.');
  print('Bye!');
}
