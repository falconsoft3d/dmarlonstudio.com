# --------------------------------------------------------------------- SQL

def lit(v, dialect):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        if dialect == "sqlite":
            return "1" if v else "0"
        return "TRUE" if v else "FALSE"
    if isinstance(v, float):
        return f"{v:.2f}"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "'" + json.dumps(v) + "'"
    return "'" + str(v).replace("'", "''") + "'"


def inserts(table, cols, rows, dialect):
    vals = ",\n".join("  (" + ", ".join(lit(v, dialect) for v in r) + ")" for r in rows)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{vals};\n"


def sql(dialect):
    if dialect == "sqlite":
        ident, money, date, boolean, js = "INTEGER PRIMARY KEY", "REAL", "TEXT", "INTEGER", "TEXT"
    elif dialect == "postgres":
        ident, money, date, boolean, js = "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "numeric(8,2)", "date", "boolean", "jsonb"
    else:
        ident, money, date, boolean, js = "INT AUTO_INCREMENT PRIMARY KEY", "DECIMAL(8,2)", "DATE", "BOOLEAN", "JSON"
    text = "VARCHAR(60)" if dialect == "mysql" else "TEXT"
    out = [f"-- {HEADER['en']}.\n-- {HEADER['es']}.\n"]
    drops = ["reviews", "order_items", "orders", "employees", "customers", "products", "categories"]
    out.append("".join(f"DROP TABLE IF EXISTS {t};\n" for t in drops))
    fk = lambda col, ref: f"{col} INTEGER REFERENCES {ref}(id)" if dialect != "mysql" else f"{col} INT, FOREIGN KEY ({col}) REFERENCES {ref}(id)"
    out.append(f"""
CREATE TABLE categories (
  id {ident},
  name {text} NOT NULL UNIQUE
);
CREATE TABLE products (
  id {ident},
  name {text} NOT NULL,
  {fk('category_id', 'categories')},
  price {money} NOT NULL,
  stock INTEGER NOT NULL DEFAULT 0,
  active {boolean} NOT NULL DEFAULT {lit(True, dialect)},
  tags {js}
);
CREATE TABLE customers (
  id {ident},
  name {text} NOT NULL,
  email {text} UNIQUE,
  city {text},
  joined {date}
);
CREATE TABLE orders (
  id {ident},
  {fk('customer_id', 'customers')},
  ordered {date} NOT NULL,
  status {text} NOT NULL DEFAULT 'new',
  total {money} NOT NULL DEFAULT 0
);
CREATE TABLE order_items (
  id {ident},
  {fk('order_id', 'orders')},
  {fk('product_id', 'products')},
  qty INTEGER NOT NULL,
  price {money} NOT NULL
);
CREATE TABLE employees (
  id {ident},
  name {text} NOT NULL,
  role {text},
  {fk('manager_id', 'employees')},
  salary {money}
);
CREATE TABLE reviews (
  id {ident},
  {fk('product_id', 'products')},
  rating INTEGER NOT NULL,
  comment {text}
);

""")
    out.append(inserts("categories", ["id", "name"], CATEGORIES, dialect))
    out.append(inserts("products", ["id", "name", "category_id", "price", "stock", "active", "tags"], PRODUCTS, dialect))
    out.append(inserts("customers", ["id", "name", "email", "city", "joined"], CUSTOMERS, dialect))
    out.append(inserts("orders", ["id", "customer_id", "ordered", "status", "total"],
                       [(o[0], o[1], o[2], o[3], TOTAL[o[0]]) for o in ORDERS], dialect))
    out.append(inserts("order_items", ["id", "order_id", "product_id", "qty", "price"], ITEM_ROWS, dialect))
    out.append(inserts("employees", ["id", "name", "role", "manager_id", "salary"], EMPLOYEES, dialect))
    out.append(inserts("reviews", ["id", "product_id", "rating", "comment"], REVIEWS, dialect))
    if dialect == "postgres":
        # Los id escritos a mano no mueven la identidad: el siguiente, tras el mayor.
        out.append("".join(
            f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), (SELECT max(id) FROM {t}));\n"
            for t in reversed(drops)))
    text = "\n".join(out)
    if dialect == "mysql":
        # Borrar en orden por las claves ajenas.
        text = text.replace("DROP TABLE IF EXISTS reviews;", "SET FOREIGN_KEY_CHECKS = 0;\nDROP TABLE IF EXISTS reviews;", 1)
        text = text.replace("DROP TABLE IF EXISTS categories;", "DROP TABLE IF EXISTS categories;\nSET FOREIGN_KEY_CHECKS = 1;", 1)
    if dialect == "postgres":
        text = "\n".join(
            l.replace(";", " CASCADE;") if l.startswith("DROP TABLE") else l for l in text.split("\n")
        )
    return text


# -------------------------------------------------------------------- JSON

def mongo():
    q = [f"// {HEADER['en']}.\n// {HEADER['es']}."]
    def ins(col, docs):
        q.append(json.dumps({"collection": col, "insert": docs}, ensure_ascii=False))
    ins("categories", [{"_id": i, "name": n} for i, n in CATEGORIES])
    ins("products", [{"_id": i, "name": n, "category_id": c, "price": p, "stock": s, "active": a, "tags": t}
                     for i, n, c, p, s, a, t in PRODUCTS])
    ins("customers", [{"_id": i, "name": n, **({"email": e} if e else {}), "city": c, "joined": j}
                      for i, n, e, c, j in CUSTOMERS])
    # Los pedidos llevan sus líneas dentro (el modelo de documentos).
    ins("orders", [{"_id": i, "customer_id": c, "ordered": d, "status": s, "total": TOTAL[i],
                    "items": [{"product_id": p, "qty": qq, "price": pr} for (_, o, p, qq, pr) in ITEM_ROWS if o == i]}
                   for i, c, d, s in ORDERS])
    ins("employees", [{"_id": i, "name": n, "role": r, "manager_id": m, "salary": s} for i, n, r, m, s in EMPLOYEES])
    ins("reviews", [{"_id": i, "product_id": p, "rating": r, **({"comment": c} if c else {})} for i, p, r, c in REVIEWS])
    return "\n".join(q) + "\n"


def firebase():
    """Firestore: identificadores de texto («p01»…) y las líneas de cada
    pedido dentro del pedido."""
    q = [f"// {HEADER['en']}.\n// {HEADER['es']}."]
    cid = lambda i: f"cat{i}"
    pid = lambda i: f"p{i:02d}"
    uid = lambda i: f"c{i}"
    oid = lambda i: f"o{i:02d}"
    def ins(col, docs):
        q.append(json.dumps({"collection": col, "insert": docs}, ensure_ascii=False))
    ins("categories", [{"_id": cid(i), "name": n} for i, n in CATEGORIES])
    ins("products", [{"_id": pid(i), "name": n, "category": cid(c), "price": p, "stock": s, "active": a, "tags": t}
                     for i, n, c, p, s, a, t in PRODUCTS])
    ins("customers", [{"_id": uid(i), "name": n, **({"email": e} if e else {}), "city": c, "joined": j}
                      for i, n, e, c, j in CUSTOMERS])
    ins("orders", [{"_id": oid(i), "customer": uid(c), "ordered": d, "status": s, "total": TOTAL[i],
                    "items": [{"product": pid(p), "qty": qq, "price": pr} for (_, o, p, qq, pr) in ITEM_ROWS if o == i]}
                   for i, c, d, s in ORDERS])
    ins("employees", [{"_id": f"e{i}", "name": n, "role": r, **({"manager": f"e{m}"} if m else {}), "salary": s}
                      for i, n, r, m, s in EMPLOYEES])
    ins("reviews", [{"_id": f"r{i}", "product": pid(p), "rating": r, **({"comment": c} if c else {})} for i, p, r, c in REVIEWS])
    return "\n".join(q) + "\n"


def falcon():
    """FalconDatabase: las tablas ya existen en el proyecto (las mismas
    columnas que en SQL, más id y created_at); aquí solo las filas."""
    q = [f"// {HEADER['en']}.\n// {HEADER['es']}."]
    def ins(table, rows):
        q.append(json.dumps({"table": table, "insert": rows}, ensure_ascii=False))
    ins("categories", [{"id": i, "name": n} for i, n in CATEGORIES])
    ins("products", [{"id": i, "name": n, "category_id": c, "price": p, "stock": s, "active": a, "tags": t}
                     for i, n, c, p, s, a, t in PRODUCTS])
    ins("customers", [{"id": i, "name": n, "email": e, "city": c, "joined": j} for i, n, e, c, j in CUSTOMERS])
    ins("orders", [{"id": i, "customer_id": c, "ordered": d, "status": s, "total": TOTAL[i]} for i, c, d, s in ORDERS])
    ins("order_items", [{"id": i, "order_id": o, "product_id": p, "qty": qq, "price": pr} for i, o, p, qq, pr in ITEM_ROWS])
    ins("employees", [{"id": i, "name": n, "role": r, "manager_id": m, "salary": s} for i, n, r, m, s in EMPLOYEES])
    ins("reviews", [{"id": i, "product_id": p, "rating": r, "comment": c} for i, p, r, c in REVIEWS])
    return "\n".join(q) + "\n"


