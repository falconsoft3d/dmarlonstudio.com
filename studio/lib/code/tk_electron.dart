import 'dart:convert';

import '../core/errors.dart';
import '../i18n/tr.dart';
import 'tk_codegen.dart';
import 'tk_electron_runtime.dart';
import 'tk_model.dart';
import 'tk_unit.dart';

/// Genera una aplicación de Electron + React a partir del diseño y del
/// código del usuario (JavaScript). Son varios archivos: el código del
/// usuario va tal cual en `Form1.js`, así sus líneas son las mismas en los
/// errores y en las herramientas de desarrollo.
class TkElectron {
  TkElectron._();

  /// Versiones con las que se crea el entorno compartido y el package.json
  /// de una aplicación exportada.
  static const electronVersion = '^45.2.0';
  static const reactVersion = '^19.2.0';

  static String _js(Object? v) => jsonEncode(v);

  /// Opciones de la ventana para main.js.
  static Map<String, Object?> window(TkDesign d) => {
    'title': d.title,
    'width': d.width,
    'height': d.height,
    'bg': TkCodegen.color(d.prop(tkFormBg)) ?? '#f0f0f0',
    'resizable': d.prop(tkFormResizable) == true,
    'topmost': d.prop(tkFormTopmost) == true,
    'position': '${d.prop(tkFormPosition)}',
    'left': TkPy.integer(d.prop(tkFormLeft)),
    'top': TkPy.integer(d.prop(tkFormTop)),
  };

  /// Propiedades de [w] para el motor (con sus valores de serie).
  static Map<String, Object?> props(TkWidget w) {
    final out = <String, Object?>{};
    for (final p in w.component.props) {
      if (p.type == TkPropType.connection || p.type == TkPropType.reference) {
        continue;
      }
      final v = w.prop(p);
      out[p.key] = switch (p.type) {
        TkPropType.color => TkCodegen.color(v),
        TkPropType.integer => TkPy.integer(v),
        TkPropType.number => v is num ? v : num.tryParse('$v') ?? 0,
        TkPropType.boolean => v == true,
        _ => '${v ?? ''}',
      };
    }
    if (w.kind == 'Listbox' || w.kind == 'Combobox') {
      out['items'] = TkCodegen.items(w);
    }
    out.removeWhere((k, v) => v == null);
    return out;
  }

  static List<Map<String, Object?>> _menu(List<TkMenuItem> items) => [
    for (final i in items)
      i.separator
          ? {'separator': true}
          : {
              'label': i.label,
              'path': i.path,
              if (i.items.isNotEmpty) 'items': _menu(i.items),
            },
  ];

  static List<Map<String, Object?>> _filters(String text) => [
    for (final line in text.split('\n'))
      if (line.contains('|'))
        if (line.split('|') case [final name, final patterns, ...])
          {
            'name': name.trim(),
            'extensions': [
              for (final p in patterns.replaceAll(',', ';').split(';'))
                if (p.trim().isNotEmpty)
                  p.trim().replaceFirst(RegExp(r'^\*?\.'), ''),
            ],
          },
    {
      'name': '*.*',
      'extensions': ['*'],
    },
  ];

  /// Lo que no es una propiedad: columnas, páginas, menú, filtros.
  static Map<String, Object?> extra(TkDesign d, TkWidget w) => switch (w.kind) {
    'Treeview' => {
      'columns': [
        for (final (field, title, width) in TkCodegen.gridColumns(w))
          {'field': field, 'title': title, 'width': ?width},
      ],
    },
    'PageControl' => {'pages': tkPages(w)},
    'Menu' => {'tree': _menu(tkMenuItems(w.text('items')))},
    'OpenDialog' || 'SaveDialog' => {'filters': _filters(w.text('filter'))},
    _ => const {},
  };

  /// La clase FormDesign: crea los componentes del diseño.
  static String design(TkDesign d) {
    final problems = d.problems();
    if (problems.isNotEmpty) throw UserError(problems.join('\n'));
    final b = StringBuffer()
      ..writeln('"use strict";')
      ..writeln('// Generated by DMarlon Studio from the design. Do not edit.')
      ..writeln()
      ..writeln('class FormDesign extends DmsForm {')
      ..writeln('  constructor() {')
      ..writeln('    super(${_js(window(d))});');
    for (final w in d.widgets) {
      final nested = w.parent != null && w.component.nestable;
      final (x, y) = TkCodegen.placeOf(d, w);
      final box = switch (w.kind) {
        'StatusBar' => [0, d.height - w.height, d.width, w.height],
        _ => [x, y, w.width, w.height],
      };
      final pc = d.pageControlOf(w);
      final args = [
        _js(w.kind),
        _js(w.name),
        nested ? _js(w.parent) : 'null',
        pc == null ? 'null' : '${w.page ?? 0}',
        _js(box),
        _js(props(w)),
        _js(w.events),
        _js(extra(d, w)),
      ];
      b.writeln('    this._add(${args.join(', ')});');
    }
    b
      ..writeln('    this._formEvents = ${_js(d.events)};')
      ..writeln('  }')
      ..writeln('}');
    return b.toString();
  }

  /// El código del usuario con un `debugger;` en cada punto de parada, en la
  /// misma línea: la numeración no cambia.
  static String withBreakpoints(String code, Map<int, String> points) {
    if (points.isEmpty) return code;
    final lines = code.split('\n');
    final masked = JsUnit.mask(code).split('\n');
    for (final MapEntry(key: line, value: cond) in points.entries) {
      final i = line - 1;
      if (i < 0 || i >= lines.length || !_statement(masked, i)) continue;
      final indent = RegExp(r'^[ \t]*').stringMatch(lines[i])!;
      final stop = cond.trim().isEmpty
          ? 'debugger; '
          : 'if (${cond.trim()}) debugger; ';
      lines[i] = '$indent$stop${lines[i].substring(indent.length)}';
    }
    return lines.join('\n');
  }

  /// ¿Empieza en la línea [i] una instrucción (donde cabe un `debugger;`)?
  static bool _statement(List<String> masked, int i) {
    final t = masked[i].trim();
    if (t.isEmpty || t == '{' || t == '}') return false;
    if (RegExp(
      r'^(\}|\)|\]|\.|else\b|catch\b|finally\b|case\b|default\b|class\b|\?|:)',
    ).hasMatch(t)) {
      return false;
    }
    // La cabecera de un método.
    if (RegExp(r'^(async\s+)?[A-Za-z_$][\w$]*\s*\([^)]*\)\s*\{$').hasMatch(t) &&
        !RegExp(r'^(if|for|while|switch|catch|with)\b').hasMatch(t)) {
      return false;
    }
    // La línea de antes sigue en esta (una expresión o un objeto abierto).
    for (var k = i - 1; k >= 0; k--) {
      final p = masked[k].trim();
      if (p.isEmpty) continue;
      if (RegExp(r'[=:(,\[+\-*/%&|?]$').hasMatch(p) ||
          RegExp(r'[=:(,]\s*\{$').hasMatch(p)) {
        return false;
      }
      break;
    }
    return true;
  }

  static const _start =
      '"use strict";\n'
      '// Generated by DMarlon Studio. Do not edit.\n'
      'require("electron").ipcRenderer.once("dms-go", () => dmsStart(%FORM%));\n';

  static String _html(String title, String unit) =>
      '<!doctype html>\n<html>\n<head>\n<meta charset="utf-8">\n'
      '<meta http-equiv="Content-Security-Policy" '
      'content="default-src \'self\' file: data:; script-src \'self\' file:; '
      'style-src \'self\' \'unsafe-inline\'; img-src \'self\' file: data:">\n'
      '<title>${const HtmlEscape().convert(title)}</title>\n'
      '<style>$tkElectronCss</style>\n</head>\n<body>\n<div id="root"></div>\n'
      '<script src="runtime.js"></script>\n<script src="design.js"></script>\n'
      '<script src="$unit"></script>\n<script src="start.js"></script>\n'
      '</body>\n</html>\n';

  /// package.json de la aplicación ([standalone]: para exportarla, con sus
  /// dependencias).
  static String packageJson(String name, {bool standalone = false}) =>
      const JsonEncoder.withIndent('  ').convert({
        'name': _npmName(name),
        'version': '1.0.0',
        'private': true,
        'main': 'main.js',
        if (standalone) ...{
          'scripts': {'start': 'electron .'},
          'dependencies': {'react': reactVersion, 'react-dom': reactVersion},
          'devDependencies': {'electron': electronVersion},
        },
      });

  static String _npmName(String name) {
    final s = name
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
        .replaceAll(RegExp(r'^-+|-+$'), '');
    return s.isEmpty ? 'dmarlon-app' : s;
  }

  /// Todos los archivos de la aplicación (nombre → contenido).
  static Map<String, String> files(
    TkDesign d,
    String code, {
    required String name,
    Map<int, String> breakpoints = const {},
    bool standalone = false,
  }) {
    final unit = code.replaceAll('\r\n', '\n');
    if (!const JsUnit().hasClass(unit, d.name)) {
      throw UserError(
        tr('El código debe definir «class {0} extends FormDesign».', [d.name]),
      );
    }
    final file = '${d.name}.js';
    return {
      'package.json': packageJson(name, standalone: standalone),
      'main.js': tkElectronMainJs,
      'window.json': const JsonEncoder.withIndent('  ').convert(window(d)),
      'index.html': _html(d.title, file),
      'runtime.js': tkElectronRuntimeJs,
      'design.js': design(d),
      file: withBreakpoints(unit, breakpoints),
      'start.js': _start.replaceAll('%FORM%', d.name),
    };
  }

  /// Lo que se ve en la pestaña «JavaScript generado»: el diseño hecho
  /// clase, seguido del código del usuario.
  static String preview(TkDesign d, String code) =>
      '${design(d)}\n\n// ---- ${d.name}.js\n\n${code.trimRight()}\n';
}
