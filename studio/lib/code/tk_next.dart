import 'dart:convert';

import '../core/errors.dart';
import '../i18n/tr.dart';
import 'tk_chrome.dart';
import 'tk_codegen.dart';
import 'tk_electron.dart';
import 'tk_electron_runtime.dart';
import 'tk_model.dart';
import 'tk_unit.dart';

/// Genera un proyecto de Next.js (app router) con el diseño como página: el
/// mismo motor de React del navegador, pasado a módulos, y el código del
/// usuario (JavaScript) con sus líneas en el mismo sitio.
class TkNext {
  TkNext._();

  static const nextVersion = '^16.0.0';

  /// El motor como módulo de ES.
  static String runtimeModule() {
    const head =
        'const DMS_HOST = window.DMS_HOST;\n'
        'const React = DMS_HOST.need("react");\n'
        'const { createRoot } = DMS_HOST.need("react-dom/client");';
    if (!tkElectronRuntimeJs.contains(head)) {
      throw StateError('El motor cambió: revise TkNext.runtimeModule.');
    }
    return '${tkElectronRuntimeJs.replaceFirst(head, 'import React from "react";\n'
        'import { createRoot } from "react-dom/client";\n'
        'import "./host";\n'
        'const DMS_HOST = window.DMS_HOST;')}\n'
        'export { DmsForm, DmsWidget, DmsView, HtmlAction, dmsStart };\n';
  }

  static String _host() =>
      '// Generated by DMarlon Studio. Do not edit.\n'
      'window.DMS_WEB = true;\n$tkChromeHostJs';

  static String _design(TkDesign d) {
    final src = TkElectron.design(d);
    return 'import { DmsForm } from "./runtime";\n'
        '${src.replaceFirst('class FormDesign extends DmsForm', 'export class FormDesign extends DmsForm')}';
  }

  /// El código del usuario como módulo: el `import` va en su primera línea,
  /// así cada línea sigue en el mismo número.
  static String unitModule(
    String code,
    String form, {
    Map<int, String> breakpoints = const {},
  }) =>
      'import { FormDesign } from "./design"; '
      '${TkElectron.withBreakpoints(code, breakpoints).trimRight()}\n\n'
      'export default $form;\n';

  static String _npmName(String name) {
    final s = name
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
        .replaceAll(RegExp(r'^-+|-+$'), '');
    return s.isEmpty ? 'dmarlon-web' : s;
  }

  static String packageJson(String name) =>
      const JsonEncoder.withIndent('  ').convert({
        'name': _npmName(name),
        'version': '1.0.0',
        'private': true,
        'scripts': {
          'dev': 'next dev --webpack',
          'build': 'next build --webpack',
          'start': 'next start',
        },
        'dependencies': {
          'next': nextVersion,
          'react': TkElectron.reactVersion,
          'react-dom': TkElectron.reactVersion,
        },
      });

  static String _css(TkDesign d) {
    final bg = TkCodegen.color(d.prop(tkFormBg)) ?? '#f0f0f0';
    return '$tkElectronCss\n'
        'body { overflow: auto; background: #e9ebef; }\n'
        '#root { width: auto; height: auto; overflow: visible; }\n'
        '.tk-form { margin: 24px auto; background: $bg; box-shadow: 0 2px 12px rgba(0,0,0,.15); }\n'
        '.tk-full { background: #fff; }\n'
        '.dms-modal { position: fixed; inset: 0; background: rgba(0,0,0,.35); display: flex; align-items: center; justify-content: center; z-index: 100; }\n'
        '.dms-modal div { background: #fff; color: #000; border-radius: 6px; padding: 14px 16px; max-width: 80%; box-shadow: 0 6px 24px rgba(0,0,0,.3); white-space: pre-wrap; }\n'
        '.dms-modal button { display: block; margin: 12px 0 0 auto; padding: 4px 14px; }\n';
  }

  /// Todos los archivos del proyecto (ruta → contenido).
  static Map<String, String> files(
    TkDesign d,
    String code, {
    required String name,
    Map<int, String> breakpoints = const {},
  }) {
    final unit = code.replaceAll('\r\n', '\n');
    if (!const JsUnit().hasClass(unit, d.name)) {
      throw UserError(
        tr('El código debe definir «class {0} extends FormDesign».', [d.name]),
      );
    }
    final title = d.title.isEmpty ? name : d.title;
    return {
      'package.json': packageJson(name),
      'next.config.mjs':
          '// Generated by DMarlon Studio.\n'
          'export default { reactStrictMode: false, agentRules: false };\n',
      'app/globals.css': _css(d),
      'app/layout.js':
          '// Generated by DMarlon Studio. Do not edit.\n'
          'import "./globals.css";\n\n'
          'export const metadata = { title: ${jsonEncode(title)} };\n\n'
          'export default function RootLayout({ children }) {\n'
          '  return (\n'
          '    <html>\n'
          '      <body>{children}</body>\n'
          '    </html>\n'
          '  );\n'
          '}\n',
      'app/page.js':
          '"use client";\n'
          '// Generated by DMarlon Studio. Do not edit.\n'
          'import dynamic from "next/dynamic";\n\n'
          '// La ventana corre en el navegador.\n'
          'const App = dynamic(() => import("./dms/app"), { ssr: false });\n\n'
          'export default function Page() {\n'
          '  return <App />;\n'
          '}\n',
      'app/dms/app.js':
          '"use client";\n'
          '// Generated by DMarlon Studio. Do not edit.\n'
          'import { useEffect } from "react";\n'
          'import { dmsStart } from "./runtime";\n'
          'import ${d.name} from "./${d.name}";\n\n'
          'let started = false;\n\n'
          'export default function App() {\n'
          '  useEffect(() => {\n'
          '    if (started) return;\n'
          '    started = true;\n'
          '    dmsStart(${d.name});\n'
          '  }, []);\n'
          '  return <div id="root" />;\n'
          '}\n',
      'app/dms/host.js': _host(),
      'app/dms/runtime.js': runtimeModule(),
      'app/dms/design.js': _design(d),
      'app/dms/${d.name}.js': unitModule(
        unit,
        d.name,
        breakpoints: breakpoints,
      ),
      'README.md':
          '# $title\n\n'
          '${tr('Aplicación web de Next.js creada con DMarlon Studio.')}\n\n'
          '```\nnpm install\nnpm run dev\n```\n',
    };
  }
}
